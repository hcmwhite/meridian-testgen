"""Write the surviving tests into the codebase's ``test/`` directory (D24).

One file per top-level requirement category — ``test_req_1.py``,
``test_req_2.py``, … — plus ``test_structural.py`` for the functions stage 2
tagged ``structural_test_only``. Those names are the whole set this tool ever
writes: a re-run overwrites exactly them and never touches, reads or deletes
anything else in ``test/``, so a hand-written test living beside the generated
ones survives every run byte for byte. The directory is created when absent.

The location is safe by construction (D24): stage 1 always skips ``test*``
directories, so generated tests can never turn up in a later parse and
describe themselves.

Each file opens with a header comment naming the tool, the run timestamp and
the two source artifacts, so a reader who finds the file in isolation can get
back to the run that produced it. Diagnostics do not live here — error notes
and token costs belong in ``testgen_report.json`` (D30).
"""

from __future__ import annotations

import ast
import json
import os
import platform
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from meridian_testgen import __version__
from meridian_testgen.generate import STRUCTURAL_GROUP
from meridian_testgen.validate import generated_test_dir

# The generated filenames, and nothing else, are ours to overwrite (D24).
CATEGORY_FILENAME_TEMPLATE = "test_req_{category}.py"
STRUCTURAL_FILENAME = "test_structural.py"


class WriterError(Exception):
    """A generated test file could not be written."""


@dataclass(frozen=True)
class WrittenFile:
    """One file this run wrote, as the report and the run command describe it."""

    path: Path
    category: str
    test_count: int

    @property
    def name(self) -> str:
        return self.path.name


def filename_for_group(group_key: str) -> str:
    """The file a group's tests land in (D24)."""
    if group_key == STRUCTURAL_GROUP:
        return STRUCTURAL_FILENAME
    return CATEGORY_FILENAME_TEMPLATE.format(category=group_key)


def ordered_group_keys(groups) -> list:
    """Category groups in code order, with the structural group last."""
    keys = [key for key in groups if key != STRUCTURAL_GROUP]
    keys.sort(key=lambda key: (not key.isdigit(), int(key) if key.isdigit() else 0, key))
    if STRUCTURAL_GROUP in groups:
        keys.append(STRUCTURAL_GROUP)
    return keys


def count_tests(source: str) -> int:
    """How many test functions *source* defines, for the report's file list."""
    try:
        tree = ast.parse(source)
    except SyntaxError:  # pragma: no cover - validated source parses
        return 0
    return sum(
        1 for node in ast.walk(tree)
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
        and node.name.startswith("test")
    )


def file_header(group_key: str, generated_at: str, mapping_ast, mapping_requirements,
                category_title: "str | None" = None) -> str:
    """The comment block every generated file opens with."""
    what = ("structural-only functions" if group_key == STRUCTURAL_GROUP
            else f"requirement category {group_key}")
    if category_title:
        what = f"{what} — {category_title}"
    return (
        f"# Generated by meridian-testgen {__version__}.\n"
        f"# Tests for {what}.\n"
        f"# Run: {generated_at}\n"
        f"# Sources: {mapping_ast}, {mapping_requirements}\n"
        "# Regenerated in place on every run — edit the requirements or the\n"
        "# code, not this file.\n"
    )


def render_file(group_key: str, grouped_tests, generated_at: str, mapping_ast,
                mapping_requirements, category_title=None) -> str:
    """The whole text of one generated test file."""
    parts = [file_header(group_key, generated_at, mapping_ast,
                         mapping_requirements, category_title)]
    for grouped in grouped_tests:
        item = grouped.item
        parts.append(
            f"\n\n# {item.dotted_name or item.unit_id} "
            f"({item.file_path}:{item.line_number}) — "
            f"requirement {item.requirement_code}\n"
            f"{grouped.source.rstrip()}\n"
        )
    return "".join(parts)


def write_test_files(codebase_root, groups, mapping_ast, mapping_requirements,
                     model=None, generated_at: "str | None" = None) -> list:
    """Write one file per group into ``<codebase>/test/`` and describe them.

    Only the D24 filenames are opened, and only for writing; a group with no
    surviving tests writes no file at all rather than an empty one, so a run
    whose every item exhausted leaves nothing behind to mistake for output.
    """
    directory = generated_test_dir(codebase_root)
    generated_at = generated_at or datetime.now(timezone.utc).isoformat()
    try:
        directory.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        raise WriterError(f"could not create {directory}: {exc}") from exc

    written: list[WrittenFile] = []
    for key in ordered_group_keys(groups):
        grouped_tests = groups.get(key) or []
        if not grouped_tests:
            continue
        title = None
        if model is not None and key != STRUCTURAL_GROUP:
            requirement = model.requirement(key)
            title = getattr(requirement, "text", None) if requirement else None
        text = render_file(key, grouped_tests, generated_at, mapping_ast,
                           mapping_requirements, title)
        path = directory / filename_for_group(key)
        try:
            path.write_text(text, encoding="utf-8")
        except OSError as exc:
            raise WriterError(f"could not write {path}: {exc}") from exc
        written.append(WrittenFile(path=path, category=key,
                                   test_count=count_tests(text)))
    return written


# --- the report artifact (D30) -------------------------------------------
#
# `testgen_report.json` is where every diagnostic of a run lives: what was
# asked of the model and what it cost, which files were written and how many
# tests each holds, how many pairs were skipped for a category-leaked
# requirement, and one error note per item that exhausted its retries (D27).
# None of that belongs in the generated test files, which stay readable
# pytest and nothing else.
#
# The envelope is the shape stages 1 and 2 already write — schema version,
# artifact name, tool, timestamp, then the inputs — with stage 2's *whole*
# envelope kept verbatim under `source_run`. Because stage 2 put stage 1's
# envelope under its own `source_run`, that one field is the entire
# traceability chain: report → mapping run → parse run.

REPORT_FILENAME = "testgen_report.json"
REPORT_SCHEMA_VERSION = 1
ARTIFACT_REPORT = "testgen_report"


def _fspath(value):
    return None if value is None else str(os.fspath(value))


def report_metadata(mapping_ast, mapping_requirements, codebase_root, out_dir,
                    interpreter, model, llm_usage=None,
                    generated_at: "str | None" = None) -> dict:
    """The report's envelope: what ran, over what, with which interpreter."""
    return {
        "schema_version": REPORT_SCHEMA_VERSION,
        "artifact": ARTIFACT_REPORT,
        "tool": f"meridian-testgen {__version__}",
        "generated_at": generated_at or datetime.now(timezone.utc).isoformat(
            timespec="seconds"),
        "inputs": {
            "mapping_ast": _fspath(mapping_ast),
            "mapping_requirements": _fspath(mapping_requirements),
            "codebase": _fspath(codebase_root),
            "out_dir": _fspath(out_dir),
        },
        "interpreter": {
            "path": _fspath(getattr(interpreter, "path", interpreter)),
            "source": getattr(interpreter, "source", None),
        },
        # Stage 2's envelope verbatim; it carries stage 1's under its own
        # `source_run`, so the whole chain hangs off this one key.
        "source_run": dict(getattr(model, "ast_meta", {}) or {}),
        "requirements_run": dict(getattr(model, "requirements_meta", {}) or {}),
        "python": platform.python_version(),
        "llm_usage": dict(llm_usage or {}),
    }


def written_file_records(written, codebase_root) -> list:
    """The written test files as the report lists them (D30).

    Paths are recorded both absolute and relative to the codebase root, since
    the report is read both by a person looking at one machine and by a later
    comparison study that only has the repository.
    """
    records = []
    for item in written:
        path = Path(item.path)
        try:
            relative = path.relative_to(Path(codebase_root))
        except ValueError:  # pragma: no cover - written under the root
            relative = path
        records.append({
            "path": str(path),
            "relative_path": str(relative),
            "category": item.category,
            "test_count": item.test_count,
        })
    return records


def build_report(mapping_ast, mapping_requirements, codebase_root, out_dir,
                 interpreter, model, written, validation_run, llm=None,
                 generated_at: "str | None" = None,
                 invocation: "dict | None" = None) -> dict:
    """The whole report body for one run, ready to serialize.

    *invocation* records how this run was started — backend, model id, and
    the argv it was launched with — so a report is reproducible on its own.
    The Codex comparison run of 2026-08-24 had to have its backend inferred
    from a zero-cost usage block; never again.
    """
    usage = getattr(llm, "usage", None)
    totals = usage.as_dict() if usage is not None else {}
    calls = usage.call_records() if usage is not None else []
    summary = validation_run.summary
    report = report_metadata(
        mapping_ast, mapping_requirements, codebase_root, out_dir, interpreter,
        model, totals, generated_at,
    )
    if invocation:
        report["invocation"] = dict(invocation)
    report["counts"] = {
        "items": summary.items,
        "valid": summary.valid,
        "exhausted": summary.exhausted,
        "attempts": summary.attempts,
        "retries_used": summary.retries_used,
        "llm_calls": summary.calls,
        "files_written": len(written),
        "tests_written": sum(f.test_count for f in written),
    }
    report["skipped_category_leak"] = summary.skipped_category_leak
    report["llm_calls"] = calls
    report["test_files"] = written_file_records(written, codebase_root)
    # Every attempt validation rejected, recovered or not — the "invalid
    # tests Meridian caught" record a results report is built from.
    report["validation_catches"] = [
        dict(catch) for catch in getattr(validation_run, "validation_catches", [])
    ]
    report["error_notes"] = [dict(note) for note in validation_run.error_notes]
    return report


def write_report(out_dir, report: dict) -> Path:
    """Write *report* as ``testgen_report.json`` in *out_dir*; return its path."""
    directory = Path(out_dir)
    path = directory / REPORT_FILENAME
    try:
        directory.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8") as handle:
            json.dump(report, handle, indent=2, sort_keys=False)
            handle.write("\n")
    except OSError as exc:
        raise WriterError(f"could not write {path}: {exc}") from exc
    return path


def run_command(interpreter, written) -> str:
    """The exact command that runs what this run wrote (D26).

    Stage 3 never runs a generated test; the run ends by handing the user the
    command so that measuring runtime behaviour stays their act, not ours.
    """
    python = _fspath(getattr(interpreter, "path", interpreter))
    paths = [record["relative_path"] if isinstance(record, dict)
             else str(record.path) for record in written]
    if not paths:
        return ""
    if len(paths) == 1:
        return f"{python} -m pytest {paths[0]}"
    # One pytest invocation PER FILE, continuing past failures: a test that
    # crashes the interpreter (a segfault in a device callback, say) then
    # costs only its own file's remainder instead of every other file's
    # results — which is what happened on the first live run (2026-08-24).
    return "; ".join(f"{python} -m pytest {path}" for path in paths)
